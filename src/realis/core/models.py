"""Data models shared by every modality (image, audio; video later)."""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, Field


class Severity(StrEnum):
    INFO = "info"
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class Status(StrEnum):
    OK = "ok"
    SKIPPED = "skipped"
    ERROR = "error"


class Finding(BaseModel):
    severity: Severity
    title: str
    detail: str = ""


class EvidenceKind(StrEnum):
    PROVENANCE = "provenance"  # origin in general: informs both questions below
    SYNTHESIS = "synthesis"  # whole image generated by AI
    MANIPULATION = "manipulation"  # local edits: splicing, cloning, inpainting
    PROCESSING = "processing"  # re-encoding / editing history


class AnalyzerResult(BaseModel):
    """Output contract every analyzer plugin must satisfy.

    score: 0.0 = evidence consistent with an authentic file, 1.0 = evidence of
    manipulation, 0.5 = no information. confidence scales how much the score
    should count when fused with other analyzers.
    """

    analyzer: str
    title: str = ""
    version: str
    status: Status
    evidence_kind: EvidenceKind = EvidenceKind.MANIPULATION
    score: float | None = None
    confidence: float = 0.0
    weight: float = 1.0
    # Set when the analyzer found provenance-grade evidence (e.g. a valid
    # C2PA manifest declaring AI generation) that should drive the verdict.
    decisive_label: str | None = None
    findings: list[Finding] = Field(default_factory=list)
    artifacts: dict[str, str] = Field(default_factory=dict)
    data: dict[str, Any] = Field(default_factory=dict)
    limitations: list[str] = Field(default_factory=list)
    elapsed_ms: float = 0.0
    error: str | None = None


class EvidenceRecord(BaseModel):
    case_id: str
    original_name: str
    stored_path: str
    sha256: str
    size_bytes: int
    ingested_at: datetime


class Contribution(BaseModel):
    analyzer: str
    score: float
    confidence: float
    weight: float
    log_odds: float


class Verdict(BaseModel):
    label: str
    # Overall: the larger of the two per-question probabilities below.
    manipulation_probability: float
    ai_generation_probability: float = 0.5
    editing_probability: float = 0.5
    # What the dominant evidence points to: "synthesis", "manipulation" or "none".
    category: str = "none"
    decisive: bool = False
    rationale: list[str]
    contributions: list[Contribution]


class Report(BaseModel):
    tool: str
    tool_version: str
    generated_at: datetime
    modality: str
    evidence: EvidenceRecord
    integrity_verified: bool
    results: list[AnalyzerResult]
    verdict: Verdict
    custody_log_valid: bool
    # Case-level figures (e.g. the audio evidence timeline): label -> case-relative path.
    overview: dict[str, str] = Field(default_factory=dict)
    notes: list[str] = Field(default_factory=list)
